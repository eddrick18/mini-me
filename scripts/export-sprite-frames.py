"""Package atlas rectangles as PNG frames without changing their source pixels."""
import json
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
assets=root/'assets/character/taller-pixel'
out=assets/'individual';out.mkdir(exist_ok=True)
groups={}
for image,manifest in [('atlas.png','frames.json'),('running-outfit.png','running-frames.json'),('sad.png','sad-frames.json'),('wave.png','wave-frames.json')]:
    sheet=Image.open(assets/image).convert('RGBA')
    for pose,frames in json.loads((assets/manifest).read_text(encoding='utf-8-sig'))['states'].items():
        names=[]
        for i,rect in enumerate(frames):
            x,y,w,h=(rect[k] for k in ('x','y','width','height'))
            frame=sheet.crop((x,y,x+w,y+h))
            assert frame.getchannel('A').getbbox(),f'Empty {pose} frame {i}'
            name=f'{pose}-{i}.png';frame.save(out/name)
            assert Image.open(out/name).convert('RGBA').tobytes()==frame.tobytes()
            names.append(name)
        groups[pose]=names
groups['runningIdle']=['windbreaker-0.png','windbreaker-1.png','windbreaker-0.png','windbreaker-1.png']
groups['runningWave']=['windbreaker-0.png','windbreaker-2.png','windbreaker-3.png','windbreaker-2.png']
lines=['// Generated by scripts/export-sprite-frames.py; static requires for Metro.','export const spriteImages={']
for pose,names in groups.items():
    lines.append(f" {pose}: ["+','.join(f"require('../../../assets/character/taller-pixel/individual/{name}')" for name in names)+'],')
lines.append('} as const;')
(root/'src/platform/animation/spriteImages.ts').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Exported and pixel-verified',sum(len(n) for n in groups.values()),'individual sprite frames')
